// Core data model for NEXUS. All dates are local calendar dates stored as 'YYYY-MM-DD'.

export type ISODate = string; // YYYY-MM-DD
export type Timestamp = number; // epoch ms

export type FieldType = 'text' | 'number' | 'date' | 'url' | 'email' | 'dropdown' | 'checkbox' | 'password' | 'textarea';

export interface FieldDef {
  id: string;
  label: string;
  type: FieldType;
  options?: string[];
}

export interface AutoTaskRule {
  enabled: boolean;
  daysBefore: number;
  title: string; // supports {name}
}

export interface Category {
  id: string;
  name: string;
  icon: string; // lucide icon name key (see icons.ts)
  color: string; // hex
  fields: FieldDef[];
  autoTask?: AutoTaskRule;
  builtin?: boolean;
}

export interface Provider {
  id: string;
  name: string;
  website: string;
  dashboardUrl: string;
  supportUrl: string;
  contact: string;
  notes: string;
  createdAt: Timestamp;
  updatedAt: Timestamp;
}

/** Value stored when field-level encryption is enabled. */
export interface EncryptedValue {
  __enc: 1;
  iv: string;
  ct: string;
}
export type SecretValue = string | EncryptedValue;

export interface RenewalRecord {
  id: string;
  at: Timestamp;
  previousExpiration?: ISODate;
  newExpiration?: ISODate;
  previousPrice?: number;
  newPrice?: number;
  note?: string;
}

export type AssetStatus = 'active' | 'paused' | 'cancelled';

export interface Attachment {
  id: string;
  name: string;
  url: string;
}

export interface Asset {
  id: string;
  name: string;
  categoryId: string;
  providerId?: string;
  purchaseUrl: string;
  purchasePrice?: number;
  currency: string;
  purchaseDate?: ISODate;
  expirationDate?: ISODate;
  renewalPrice?: number;
  loginUrl: string;
  username: string;
  password?: SecretValue;
  notes: string;
  tags: string[];
  status: AssetStatus;
  custom: Record<string, string | number | boolean | EncryptedValue | undefined>;
  attachments: Attachment[];
  pinned: boolean;
  notificationsEnabled: boolean;
  reminderDays?: number[] | null; // null/undefined -> use global default
  snoozedUntil?: ISODate;
  renewals: RenewalRecord[];
  createdAt: Timestamp;
  updatedAt: Timestamp;
}

export type Priority = 'low' | 'medium' | 'high' | 'urgent';
export type Recurrence = 'none' | 'daily' | 'weekly' | 'monthly' | 'yearly';

export interface Subtask {
  id: string;
  title: string;
  done: boolean;
}

export interface Task {
  id: string;
  title: string;
  description: string;
  dueDate?: ISODate;
  reminderAt?: string; // 'YYYY-MM-DDTHH:mm' local
  priority: Priority;
  tags: string[];
  done: boolean;
  completedAt?: Timestamp;
  assetId?: string;
  recurrence: Recurrence;
  subtasks: Subtask[];
  pinned: boolean;
  autoRenewal?: boolean; // generated by renewal rule
  createdAt: Timestamp;
  updatedAt: Timestamp;
}

export type ActivityType =
  | 'asset.created'
  | 'asset.edited'
  | 'asset.deleted'
  | 'asset.renewed'
  | 'asset.expiration'
  | 'asset.provider'
  | 'asset.category'
  | 'task.created'
  | 'task.completed'
  | 'task.reopened'
  | 'task.deleted'
  | 'task.edited'
  | 'provider.created'
  | 'provider.edited'
  | 'provider.deleted'
  | 'data.imported';

export interface Activity {
  id: string;
  type: ActivityType;
  itemType: 'asset' | 'task' | 'provider' | 'data';
  itemId?: string;
  itemName: string;
  summary: string;
  at: Timestamp;
}

export type Theme = 'system' | 'light' | 'dark';
export type AssetView = 'table' | 'list' | 'grid';
export type Density = 'compact' | 'comfortable';
export type DateFormat = 'MMM d, yyyy' | 'yyyy-MM-dd' | 'dd/MM/yyyy' | 'MM/dd/yyyy';

export type DashboardSectionId = 'expirations' | 'today' | 'activity' | 'quick' | 'monthly';

export interface Settings {
  userName: string;
  language: 'en' | 'fa';
  calendar: 'gregorian' | 'jalali';
  theme: Theme;
  defaultView: AssetView;
  density: Density;
  dateFormat: DateFormat;
  currency: string;
  weekStart: 0 | 1 | 6;
  notificationsEnabled: boolean;
  reminderDays: number[];
  taskReminders: boolean;
  dailyDigest: boolean;
  autoRenewalTask: boolean;
  renewalTaskDays: number;
  dashboardSections: { id: DashboardSectionId; visible: boolean }[];
  paletteShortcut: string; // e.g. 'mod+k'
  encryption: { enabled: boolean; salt?: string; verifier?: EncryptedValue };
  pinOrder: string[]; // 'asset:<id>' | 'task:<id>'
}

export interface DB {
  version: number;
  assets: Asset[];
  tasks: Task[];
  providers: Provider[];
  categories: Category[];
  activity: Activity[];
  settings: Settings;
}

export interface NotificationLogEntry {
  id: string;
  kind: 'expiration' | 'task' | 'digest';
  itemId?: string;
  title: string;
  message: string;
  at: Timestamp;
  read?: boolean;
}

/** Stored separately (key nexus_notify) so the service worker never clobbers UI writes. */
export interface NotifyState {
  sent: Record<string, Timestamp>;
  log: NotificationLogEntry[];
}

export type ExpiryStatus = 'normal' | 'warning' | 'critical' | 'expired' | 'none';
